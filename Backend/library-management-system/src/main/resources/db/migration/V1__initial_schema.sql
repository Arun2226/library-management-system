
-- ==========================================
-- LIBRARY MANAGEMENT SYSTEM
-- PostgreSQL database schema
-- ==========================================

-- 1. USERS
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       full_name VARCHAR(150) NOT NULL,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       password_hash VARCHAR(255) NOT NULL,
                       role VARCHAR(20) NOT NULL
                           CHECK (role IN ('ADMIN', 'LIBRARIAN', 'MEMBER')),
                       is_active BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. MEMBERS
CREATE TABLE members (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         user_id BIGINT NOT NULL UNIQUE
                             REFERENCES users(id) ON DELETE RESTRICT,
                         member_number VARCHAR(30) NOT NULL UNIQUE,
                         phone VARCHAR(20),
                         joined_at DATE NOT NULL DEFAULT CURRENT_DATE,
                         status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                             CHECK (status IN ('ACTIVE', 'SUSPENDED', 'INACTIVE'))
);

-- 3. BOOKS
CREATE TABLE books (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       isbn VARCHAR(20) UNIQUE,
                       title VARCHAR(255) NOT NULL,
                       author VARCHAR(150) NOT NULL,
                       publisher VARCHAR(150),
                       category VARCHAR(100),
                       publication_year INTEGER
                           CHECK (publication_year IS NULL OR publication_year BETWEEN 1 AND 9999),
                       description TEXT,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. BOOK COPIES
CREATE TABLE book_copies (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             book_id BIGINT NOT NULL
                                 REFERENCES books(id) ON DELETE RESTRICT,
                             accession_number VARCHAR(50) NOT NULL UNIQUE,
                             status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
                                 CHECK (status IN (
                                                   'AVAILABLE', 'BORROWED', 'RESERVED',
                                                   'LOST', 'DAMAGED', 'IN_REPAIR'
                                     )),
                             acquired_at DATE
);

-- 5. BORROWINGS
CREATE TABLE borrowings (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            member_id BIGINT NOT NULL
                                REFERENCES members(id) ON DELETE RESTRICT,
                            copy_id BIGINT NOT NULL
                                REFERENCES book_copies(id) ON DELETE RESTRICT,
                            issued_by BIGINT NOT NULL
                                REFERENCES users(id) ON DELETE RESTRICT,
                            received_by BIGINT
                                REFERENCES users(id) ON DELETE RESTRICT,
                            borrowed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            due_at TIMESTAMPTZ NOT NULL,
                            returned_at TIMESTAMPTZ,
                            status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                                CHECK (status IN ('ACTIVE', 'RETURNED', 'LOST')),
                            CONSTRAINT chk_borrowing_due_date
                                CHECK (due_at > borrowed_at),
                            CONSTRAINT chk_borrowing_return_date
                                CHECK (
                                    (status = 'RETURNED' AND returned_at IS NOT NULL)
                                        OR
                                    (status <> 'RETURNED' AND returned_at IS NULL)
                                    )
);

-- 6. RESERVATIONS
CREATE TABLE reservations (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              member_id BIGINT NOT NULL
                                  REFERENCES members(id) ON DELETE RESTRICT,
                              book_id BIGINT NOT NULL
                                  REFERENCES books(id) ON DELETE RESTRICT,
                              status VARCHAR(20) NOT NULL DEFAULT 'WAITING'
                                  CHECK (status IN (
                                                    'WAITING', 'READY', 'FULFILLED',
                                                    'CANCELLED', 'EXPIRED'
                                      )),
                              requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              fulfilled_at TIMESTAMPTZ
);

-- 7. FINES
CREATE TABLE fines (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       borrowing_id BIGINT NOT NULL UNIQUE
                           REFERENCES borrowings(id) ON DELETE RESTRICT,
                       amount NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
                       status VARCHAR(20) NOT NULL DEFAULT 'UNPAID'
                           CHECK (status IN ('UNPAID', 'PAID', 'WAIVED')),
                       paid_at TIMESTAMPTZ,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                       CONSTRAINT chk_fine_paid_at
                           CHECK (
                               (status = 'PAID' AND paid_at IS NOT NULL)
                                   OR
                               (status <> 'PAID' AND paid_at IS NULL)
                               )
);

-- 8. AUDIT LOGS
CREATE TABLE audit_logs (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            actor_user_id BIGINT
                                                   REFERENCES users(id) ON DELETE SET NULL,
                            action VARCHAR(100) NOT NULL,
                            entity_type VARCHAR(100),
                            entity_id BIGINT,
                            details JSONB NOT NULL DEFAULT '{}'::jsonb,
                            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ==========================================
-- BUSINESS RULE ENFORCEMENT
-- ==========================================

-- A physical copy can have only one active borrowing.
CREATE UNIQUE INDEX uq_active_borrowing_copy
    ON borrowings(copy_id)
    WHERE status = 'ACTIVE';

-- A member cannot have duplicate active reservations
-- for the same book.
CREATE UNIQUE INDEX uq_active_member_reservation
    ON reservations(member_id, book_id)
    WHERE status IN ('WAITING', 'READY');

-- ==========================================
-- PERFORMANCE INDEXES
-- ==========================================

CREATE INDEX idx_books_title ON books(title);
CREATE INDEX idx_books_category ON books(category);
CREATE INDEX idx_book_copies_book_id ON book_copies(book_id);
CREATE INDEX idx_borrowings_member_id ON borrowings(member_id);
CREATE INDEX idx_borrowings_due_at ON borrowings(due_at);
CREATE INDEX idx_borrowings_issued_by ON borrowings(issued_by);
CREATE INDEX idx_reservations_book_queue
    ON reservations(book_id, requested_at, id)
    WHERE status = 'WAITING';
CREATE INDEX idx_fines_status ON fines(status);
CREATE INDEX idx_audit_logs_created_at ON audit_logs(created_at);
CREATE INDEX idx_audit_logs_actor ON audit_logs(actor_user_id);

